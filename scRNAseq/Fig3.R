save_panel <- function(plot_object, file_stem, width_mm, height_mm) {
  ggplot2::ggsave(
    filename = paste0(file_stem, ".pdf"),
    plot = plot_object,
    device = grDevices::cairo_pdf,
    width = width_mm,
    height = height_mm,
    units = "mm",
    bg = "white",
    limitsize = FALSE
  )
  ggplot2::ggsave(
    filename = paste0(file_stem, ".png"),
    plot = plot_object,
    device = ragg::agg_png,
    width = width_mm,
    height = height_mm,
    units = "mm",
    dpi = 300,
    bg = "white",
    limitsize = FALSE
  )
}

format_p_value <- function(p_value) {
  if (base::is.na(p_value)) {
    return("NA")
  }
  if (p_value < 2.22e-16) {
    return("< 2.22e-16")
  }
  if (p_value < 0.001) {
    return(base::formatC(p_value, format = "e", digits = 2))
  }
  base::formatC(p_value, format = "f", digits = 3)
}

p_to_star <- function(p_value) {
  if (base::is.na(p_value)) return("NA")
  if (p_value < 0.001) return("***")
  if (p_value < 0.01) return("**")
  if (p_value < 0.05) return("*")
  "ns"
}

