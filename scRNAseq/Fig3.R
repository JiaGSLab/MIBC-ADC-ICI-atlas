prepare_expression_panel <- function(
  object,
  target_subtypes,
  genes,
  subtype_levels
) {
  object_meta <- object@meta.data
  keep_cells <- base::rownames(object_meta)[
    base::as.character(object_meta$Time_point) == "Pre" &
      base::as.character(object_meta$Group) %in% c("Pre_NR", "Pre_CR") &
      base::as.character(object_meta$subcelltype) %in% target_subtypes
  ]
  object <- base::subset(object, cells = keep_cells)
  Seurat::DefaultAssay(object) <- "RNA"

  object$Group <- base::factor(
    base::as.character(object$Group),
    levels = c("Pre_NR", "Pre_CR")
  )
  object$subcelltype <- base::factor(
    base::as.character(object$subcelltype),
    levels = subtype_levels
  )
  Seurat::Idents(object) <- "subcelltype"

  fetched <- Seurat::FetchData(
    object = object,
    vars = c("sample", "Outcome", "Group", "subcelltype", genes),
    layer = "data",
    clean = FALSE
  )
  fetched$cell <- base::rownames(fetched)

  long_data <- tidyr::pivot_longer(
    fetched,
    cols = dplyr::all_of(genes),
    names_to = "gene",
    values_to = "expression"
  )
  long_data$gene <- base::factor(long_data$gene, levels = genes)
  long_data$Group <- base::factor(
    base::as.character(long_data$Group),
    levels = c("Pre_NR", "Pre_CR")
  )
  long_data$subcelltype <- base::factor(
    base::as.character(long_data$subcelltype),
    levels = subtype_levels
  )

  list(object = object, cell_data = long_data)
}

calculate_sample_level_wilcoxon <- function(cell_data) {
  sample_data <- cell_data |>
    dplyr::group_by(sample, Group, subcelltype, gene) |>
    dplyr::summarise(
      mean_expression = base::mean(expression, na.rm = TRUE),
      cell_count = dplyr::n(),
      .groups = "drop"
    )

  split_data <- base::split(
    sample_data,
    interaction(sample_data$gene, sample_data$subcelltype, drop = TRUE)
  )

  stats_list <- base::lapply(split_data, function(one_test) {
    nr_values <- one_test$mean_expression[
      base::as.character(one_test$Group) == "Pre_NR"
    ]
    cr_values <- one_test$mean_expression[
      base::as.character(one_test$Group) == "Pre_CR"
    ]

    p_value <- NA_real_
    if (base::length(nr_values) >= 2L && base::length(cr_values) >= 2L) {
      p_value <- stats::wilcox.test(
        x = nr_values,
        y = cr_values,
        alternative = "two.sided",
        exact = FALSE
      )$p.value
    }

    data.frame(
      gene = base::as.character(one_test$gene[1]),
      subcelltype = base::as.character(one_test$subcelltype[1]),
      n_Pre_NR = base::length(nr_values),
      n_Pre_CR = base::length(cr_values),
      mean_Pre_NR = base::mean(nr_values, na.rm = TRUE),
      mean_Pre_CR = base::mean(cr_values, na.rm = TRUE),
      median_Pre_NR = stats::median(nr_values, na.rm = TRUE),
      median_Pre_CR = stats::median(cr_values, na.rm = TRUE),
      mean_difference_NR_minus_CR =
        base::mean(nr_values, na.rm = TRUE) - base::mean(cr_values, na.rm = TRUE),
      p_value = p_value,
      stringsAsFactors = FALSE
    )
  })

  stats_data <- base::do.call(base::rbind, stats_list)
  stats_data$p_adjust_BH <- stats::p.adjust(stats_data$p_value, method = "BH")
  stats_data$significance <- base::vapply(
    stats_data$p_adjust_BH,
    p_to_star,
    character(1)
  )
  base::rownames(stats_data) <- NULL

  list(sample_data = sample_data, stats_data = stats_data)
}

