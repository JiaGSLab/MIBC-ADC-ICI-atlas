    group.by = "subcelltype",
    split.by = "Group",
    split.plot = TRUE,
    layer = "data",
    combine = FALSE,
    fill.by = "ident"
  )

  for (plot_index in base::seq_along(plot_list)) {
    gene_name <- genes[plot_index]
    one_plot <- plot_list[[plot_index]]

