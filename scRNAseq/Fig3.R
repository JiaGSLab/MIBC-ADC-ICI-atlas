        )
      ) +
      ggplot2::scale_y_continuous(
        expand = ggplot2::expansion(
          mult = c(0.02, if (annotation == "none") 0.08 else 0.22)
        )
      ) +
      ggplot2::coord_cartesian(clip = "off") +
      ggplot2::theme(
        axis.text.x = ggplot2::element_text(
          family = "Arial", size = 8, colour = "black",
          angle = 45, hjust = 1, vjust = 1
        ),
        axis.title.y = if (plot_index == 1L) {
          ggplot2::element_text(
            family = "Arial", size = 8, colour = "black",
            margin = ggplot2::margin(r = 0.8, unit = "mm")
          )
        } else {
          ggplot2::element_blank()
        },
        legend.position = if (show_legend && plot_index == base::length(plot_list)) {
          "right"
        } else {
          "none"
        },
        legend.title = ggplot2::element_blank(),
        legend.key.height = grid::unit(3.2, "mm"),
        plot.margin = ggplot2::margin(
          2.0,
          0.5,
          1.0,
          if (plot_index == 1L) 4.5 else 0.8,
          unit = "mm"
        )
      )

    if (annotation != "none" && !base::is.null(stats_data)) {
      annotation_data <- stats_data[
        stats_data$gene == gene_name &
          stats_data$subcelltype %in% subtype_levels,
        ,
        drop = FALSE
      ]
      annotation_data$subcelltype <- base::factor(
        annotation_data$subcelltype,
        levels = subtype_levels
      )
      annotation_data$y <- base::vapply(
        base::as.character(annotation_data$subcelltype),
        function(subtype_name) {
          values <- cell_data$expression[
            base::as.character(cell_data$gene) == gene_name &
              base::as.character(cell_data$subcelltype) == subtype_name
          ]
          value_max <- base::max(values, na.rm = TRUE)
          if (!base::is.finite(value_max) || value_max <= 0) 0.1 else value_max * 1.04
        },
        numeric(1)
      )
      annotation_data$label <- if (annotation == "star") {
        annotation_data$significance
      } else {
        base::paste0(
          "p = ",
          base::vapply(annotation_data$p_adjust_BH, format_p_value, character(1))
        )
      }

      one_plot <- one_plot +
        ggplot2::geom_text(
          data = annotation_data,
          mapping = ggplot2::aes(
            x = subcelltype,
            y = y,
            label = label
          ),
          inherit.aes = FALSE,
          family = "Arial",
          size = 8 / ggplot2::.pt,
          colour = "black",
          vjust = 0
        )
    }

    plot_list[[plot_index]] <- one_plot
  }

  patchwork::wrap_plots(plot_list, nrow = 1)
}

